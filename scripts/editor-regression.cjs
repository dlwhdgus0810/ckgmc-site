const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
// Requires a local development admin and Playwright. No content POST reaches the server.
const base = (process.env.BASE_URL || 'http://localhost:4321').replace(/\/$/, '');
const target = new URL(base);
if (!['localhost', '127.0.0.1', '[::1]'].includes(target.hostname) || !['http:', 'https:'].includes(target.protocol)) throw new Error('BASE_URL must be a loopback development server.');
const adminEmail = process.env.TEST_ADMIN_EMAIL || 'admin@example.com';
const artifactDir = process.env.ARTIFACT_DIR || os.tmpdir();
fs.mkdirSync(artifactDir, { recursive: true });
(async () => {
  const browser = await chromium.launch({ ...(process.env.CHROMIUM_PATH ? {executablePath: process.env.CHROMIUM_PATH} : {}), headless: true, args: ['--no-sandbox'] });
  const context = await browser.newContext({viewport:{width:1366,height:900}});
  const page = await context.newPage(); const checks = [], errors = [];
  page.on('pageerror', e => errors.push(e.message));
  // All content mutations are intercepted. Login only creates a local development session.
  let blockedPosts = 0;
  await page.route('**/manage/content/**', route => { if (route.request().method() === 'POST') { blockedPosts++; return route.abort(); } return route.continue(); });
  try {
    await page.goto(base + '/login?next=/manage', {waitUntil:'networkidle', timeout:90000});
    await page.locator('form.dev-login input[name=email]').fill(adminEmail);
    await Promise.all([page.waitForURL(url => !url.pathname.startsWith('/login')), page.locator('form.dev-login button').click()]);
    await page.goto(base + '/manage/content/settings/edit', {waitUntil:'networkidle'});
    await page.locator('form[data-draft-ready]').waitFor();
    assert.ok(await page.locator('.cf-section').count() >= 5);
    assert.equal(await page.locator('details.cf-section[open]').count(), 1);
    assert.equal(await page.locator('.cf-actions').evaluate(el => getComputedStyle(el).position), 'sticky');
    checks.push('Grouped settings and sticky publishing actions');
    const invalidName = page.locator('input[name=name]'); const validName = await invalidName.inputValue();
    await invalidName.fill(''); await page.locator('.cf-actions button[type=submit]').click();
    assert.equal(await invalidName.getAttribute('aria-invalid'), 'true');
    assert.ok(await page.locator('[data-editor-errors]').isVisible());
    assert.equal(blockedPosts, 0); await invalidName.fill(validName);
    checks.push('Invalid fields reveal errors and block publishing');
    const name = page.locator('input[name=name]'); const original = await name.inputValue();
    await name.fill(original + ' 임시검증');
    assert.match(await page.locator('[data-draft-status]').innerText(), /변경된 입력 1개/);
    page.once('dialog', d => d.dismiss());
    await page.locator('.cf-actions a').filter({hasText:'목록으로'}).click();
    assert.ok(page.url().includes('/settings/edit'));
    checks.push('Dirty navigation guard cancels leaving');
    await page.locator('[data-preview-open]').click();
    await page.locator('dialog[open]').waitFor();
    assert.equal(await page.locator('[data-preview-frame]').getAttribute('sandbox'), '');
    await page.frameLocator('[data-preview-frame]').getByRole('heading', {name:original + ' 임시검증'}).waitFor();
    await page.locator('[data-preview-close]').click();
    checks.push('Sandboxed preview displays unsaved input');
    page.once('dialog', d => d.accept());
    await page.reload({waitUntil:'networkidle'});
    assert.equal(await name.inputValue(), original);
    await page.getByRole('button', {name:'임시 입력 복원',exact:true}).click();
    assert.equal(await name.inputValue(), original + ' 임시검증');
    checks.push('Reload offers recovery and restores field values');
    await page.locator('.cf-section-nav a[href="#editor-worship"]').click();
    const list = page.locator('[data-list="serviceTimes"]');
    const rowNames = () => list.locator('[data-list-row] input[name$=".name"]').evaluateAll(es => es.map(el=>el.value));
    const before = await rowNames(); assert.ok(before.length >= 2);
    await list.locator('[data-list-row]').first().locator('[data-list-down]').click();
    const reordered = await rowNames(); assert.equal(reordered[0], before[1]); assert.equal(reordered[1], before[0]);
    const formKeys = await list.locator('[data-list-row]').first().locator('input[name$=".name"]').getAttribute('name');
    assert.equal(formKeys,'serviceTimes[0].name');
    await list.locator('[data-list-row]').first().locator('[data-list-remove]').click();
    assert.equal((await rowNames()).length, before.length - 1);
    await list.locator('[data-list-undo]').click();
    assert.deepEqual(await rowNames(), reordered);
    checks.push('Repeated rows reorder submitted indices and undo deletion');
    page.once('dialog', d=>d.accept()); await page.reload({waitUntil:'networkidle'});
    await page.getByRole('button', {name:'임시 입력 복원',exact:true}).click();
    assert.deepEqual(await rowNames(), reordered);
    checks.push('Recovery retains repeated row order');
    await page.setViewportSize({width:390,height:844});
    await page.evaluate(()=>scrollTo(0,0));
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth + 1));
    await page.screenshot({path:path.join(artifactDir,'ckgmc-editor-settings-mobile.png'),fullPage:false});
    checks.push('Settings fit 390px viewport');
    await page.setViewportSize({width:320,height:844});
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth + 1));
    checks.push('Settings fit 320px viewport');
    page.once('dialog', d=>d.accept());
    await page.goto(base+'/manage/content/pages_about/edit?path=src%2Fcontent%2Fpages%2Fabout%2Fservices.md',{waitUntil:'networkidle'});
    const body = page.locator('textarea[name=body]'); const source = await body.inputValue();
    assert.ok(await page.locator('[data-page-fields] textarea').count()>0);
    const originalPage = fs.readFileSync(path.join(__dirname, '../src/content/pages/about/services.md'), 'utf8');
    const expectedBody = /^---\r?\n[\s\S]*?\r?\n---\r?\n?([\s\S]*)$/.exec(originalPage)[1].replace(/^\r?\n/, '');
    assert.equal(source, expectedBody, 'Opening the visual editor must preserve original HTML exactly');
    const pageText=page.locator('[data-page-fields] textarea').first(); const pageOriginal=await pageText.inputValue();
    await pageText.fill(pageOriginal+' 변경검증');
    const edited = await body.inputValue(); assert.ok(edited.includes('변경검증'));
    const originalClasses = Array.from(source.matchAll(/class="([^"]*)"/g)).map(x=>x[1]);
    for(const cls of originalClasses) assert.ok(edited.includes(`class="${cls}"`));
    await page.locator('[data-preview-open]').click();
    await page.frameLocator('[data-preview-frame]').locator('body').getByText(pageOriginal+' 변경검증',{exact:false}).first().waitFor();
    await page.locator('[data-preview-close]').click();
    checks.push('Visual page editing preserves existing classes and previews current text');
    page.once('dialog', d=>d.accept());
    await page.goto(base+'/manage/content/sermons',{waitUntil:'networkidle'});
    assert.equal(await page.getByLabel('제목 또는 파일 이름 검색').count(),1);
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth + 1));
    if(await page.locator('tbody tr').count()) assert.ok(await page.locator('tbody tr').first().locator('td[data-label="작업"]').isVisible());
    checks.push('Mobile content list has labeled search and visible actions');
    await page.goto(base+'/manage/content/settings/edit#editor-news',{waitUntil:'networkidle'});
    assert.ok(await page.locator('#editor-news').evaluate(el=>el.open));
    checks.push('Notice-review shortcut opens its section');
    assert.equal(blockedPosts,0);
    assert.deepEqual(errors,[]);
    console.log(JSON.stringify({ok:true,checks,errors},null,2));
  } catch(error) { console.log(JSON.stringify({ok:false,error:error.stack,url:page.url(),checks,errors},null,2)); await page.screenshot({path:path.join(artifactDir,'ckgmc-editor-regression-failure.png'),fullPage:false}).catch(()=>{}); process.exitCode=1; }
  finally {await browser.close();}
})();
