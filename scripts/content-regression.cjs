const { chromium } = require('playwright');
const assert = require('node:assert/strict');
(async () => {
 const browser = await chromium.launch({ headless: true, ...(process.env.CHROMIUM_PATH ? { executablePath: process.env.CHROMIUM_PATH } : {}) });
 const context = await browser.newContext({viewport:{width:390,height:844}, reducedMotion:'reduce'});
 const page = await context.newPage();
 try {
 const errors=[]; page.on('pageerror', e => errors.push(e.message));

 const base=(process.env.BASE_URL || 'http://localhost:4321').replace(/\/$/, '');
 await page.route('**/*', route => {
  const url = new URL(route.request().url());
  if (url.origin === new URL(base).origin) return route.continue();
  if (url.hostname === 'www.youtube.com' && url.pathname.startsWith('/embed/')) return route.fulfill({status:200,contentType:'text/html',body:'<p>Video provider test fixture</p>'});
  return route.abort();
 });
 const go=async path => { await page.goto(base+path,{waitUntil:'domcontentloaded'}); };
 let failOnce=true, requests=0;
 await page.route('**/search/sermons.json', async route => { requests++; if(failOnce){failOnce=false;await route.fulfill({status:503,body:'Unavailable'});}else await route.continue(); });
 await go('/media/sermons');
 await page.locator('[data-board-search]').waitFor({state:'visible'});
 assert((await page.locator('[data-board-list] .card-tile').first().boundingBox()).height < 240, 'Mobile sermon card compact');
 assert(!/LIVE/i.test(await page.locator('[data-board-list]').innerText()),'Recorded cards omit LIVE');
 await page.waitForFunction(()=>document.querySelector('[data-board-list] .card-tile img').src.endsWith('/images/thumbnail-default.jpg'));

 await page.locator('#board-q').fill('사도행전');
 await page.locator('[data-search-retry]').waitFor({state:'visible'});
 assert(await page.locator('[data-board-list]').isVisible(),'Base list stays available on failure');
 await page.locator('[data-search-retry]').click();
 await page.locator('[data-search-results] .card-tile').first().waitFor();
 assert(requests>=2,'Rejected search promise can retry');
 await page.locator('#board-year').selectOption('2026');
 await page.waitForFunction(()=>document.querySelector('[data-search-status]').textContent.includes('개 중'));
 const serviceOptions=await page.locator('#board-service option').allTextContents();
 assert(serviceOptions.length>1,'Service filter available');
 await page.locator('#board-q').fill('');
 await page.waitForFunction(()=>!new URL(location.href).searchParams.has('q'));
 const more=page.locator('[data-search-results] button').filter({hasText:'더 보기'});
 if(await more.isVisible()) { await more.click(); await page.waitForFunction(()=>new URL(location.href).searchParams.get('count')==='30'); }
 const result=page.locator('[data-search-results] .card-tile').nth(8);
 await result.scrollIntoViewIfNeeded();
 await result.click();
 await page.waitForFunction(()=>document.querySelector('[data-return-to]')?.textContent.includes('검색 결과'));
 assert(new URL(page.url()).searchParams.has('returnTo'),'Detail keeps list context');
 const saved=await page.evaluate(()=>JSON.parse(sessionStorage.getItem('ckgmc:board:/media/sermons')));
 assert((await page.locator('[data-return-to]').textContent()).includes('검색 결과'),'Contextual back label');
 assert(await page.locator('.media-fallback a').isVisible(),'External video fallback');
 await page.locator('[data-return-to]').click();
 await page.locator('[data-search-results] .card-tile').first().waitFor();

 assert.equal(await page.locator('#board-year').inputValue(),'2026');
 await page.waitForFunction(y=>Math.abs(scrollY-y)<10,saved.y);
 assert(Math.abs(await page.evaluate(()=>scrollY)-saved.y)<10,'List scroll restored');
 assert(await page.locator('[data-search-results] .card-tile').count()>=15);
 await go('/media/sermons/page/2');
 await page.locator('[data-board-search]').waitFor({state:'visible'});
 await page.locator('[data-board-list] .card-tile').first().click();
 await page.waitForFunction(()=>document.querySelector('[data-return-to]')?.getAttribute('href').includes('/page/2'));
 await page.locator('[data-return-to]').click();
 assert.equal(new URL(page.url()).pathname,'/media/sermons/page/2','Pagination retained');
 await go('/media/sermons?year=2026');
 await page.locator('[data-search-results] .card-tile').first().waitFor();
 const service=await page.locator('#board-service option').nth(1).getAttribute('value');
 await page.locator('#board-service').selectOption(service);
 await page.waitForFunction(value=>new URL(location.href).searchParams.get('service')===value,service);
 assert((await page.locator('[data-search-results] .card-tile__eyebrow').allTextContents()).every(text=>text===service),'Service filter applies to every result');
 await go('/media/bulletins');
 await page.locator('[data-board-search]').waitFor({state:'visible'});
 const first=page.locator('.post-row').first();
 const title=await first.locator('.post-row__title').textContent();
 const date=await first.locator('time').getAttribute('datetime');
 assert(title.includes(date.replaceAll('-','.')),'Bulletin title and service date agree');
 await first.locator('.post-row__main').click();
 await page.locator('[data-file-size]').waitFor();
 await page.waitForFunction(()=>document.querySelector('[data-file-size]')?.textContent.length>0);
 assert(/KB|MB/.test(await page.locator('[data-file-size]').textContent()),'Accurate file size available');
 const index=await page.request.get(base+'/search/sermons.json').then(r=>r.json());
 assert(index.some(i=>i.k?.length>300),'Full public body indexed beyond excerpt');
 await go('/media/series/51');
 assert(!(await page.locator('[data-episode-controls]').isVisible()));
 await page.locator('[data-no="2"]').click();
 const episode=new URL(page.url()).searchParams.get('episode');
 assert(episode,'Selected episode in URL');
 await page.reload({waitUntil:'domcontentloaded'});
 await page.locator('[data-episode-controls]').waitFor({state:'visible'});
 assert.equal(await page.locator('[aria-current="true"][data-youtube-id]').getAttribute('data-no'),'2');
 await page.locator('[data-episode-prev]').click();
 assert.equal(await page.locator('[aria-current="true"][data-youtube-id]').getAttribute('data-no'),'1');
 assert(await page.locator('[data-episode-prev]').isDisabled());
 await page.locator('[data-episode-next]').click();
 assert.equal(new URL(page.url()).searchParams.get('episode'),episode);
 await page.locator('#episode-search').fill('검색결과없음ZZZ');
 assert.equal(await page.locator('.episode:visible').count(),0);
 assert((await page.locator('[data-episode-search-status]').textContent()).includes('0개'));
 await page.locator('#episode-search').fill('');
 assert(await page.locator('.episode:visible').count()>5);
 await go('/story/2026-04-24-1283812653873852');
 assert.equal(await page.locator('h1').count(),1);
 assert((await page.locator('h1').textContent()).includes('월간청년'));
 const opener=page.locator('[data-gallery-image]').first();
 await opener.click();
 await page.locator('dialog[open]').waitFor();
 assert((await page.locator('#gallery-caption').textContent()).includes('1 / 7'));
 await page.keyboard.press('ArrowRight');
 assert((await page.locator('#gallery-caption').textContent()).includes('2 / 7'));
 await page.keyboard.press('Escape');
 assert(!(await page.locator('dialog').isVisible()));
 assert(await opener.evaluate(el=>document.activeElement===el),'Gallery restores focus');
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,'No horizontal mobile overflow');
 for(const width of [360,768,1280]) {
  await page.setViewportSize({width,height:900});
  await go('/media/sermons');
  await page.locator('[data-board-search]').waitFor({state:'visible'});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,`No board overflow at ${width}px`);
 }
 assert.equal(errors.length,0,`Browser errors: ${errors.join('; ')}`);
 console.log(JSON.stringify({passed:['08 retry','09 list search/page/scroll context','23 compact mobile/service filter','24 bulletin service date','25 fulltext index','26 recorded labels','27 series URLs/reload/prev-next/search','28 story H1','29 PDF filesize','30 external fallback','31 gallery keyboard/focus'],requests}));
 } finally { await browser.close(); }
})().catch(e=>{console.error(e);process.exit(1)});
